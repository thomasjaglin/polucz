export type WordType = 'verb' | 'noun' | 'adjective' | 'unknown'

export type PageId =
  | 'folder'
  | 'translate'
  | 'dynamic_feed'
  | 'question_mark'
  | 'spatial_audio'
  | 'add_page'
  | 'api_config'

export interface PageConfig {
  title: string
  icon: string
  desc: string
  gradient: string
}

// ─── Vocab entry sub-shapes ────────────────────────────────────────────────

export interface VerbConjugations {
  present: string[]
  past: string[]
  past2: string[]
}

export interface NounDeclensions {
  cases: string[]
  singular: string[]
  plural: string[]
}

// ─── Discriminated union for VocabEntry ────────────────────────────────────

interface VocabBase {
  id: string        // lemma — dedup key for localStorage
  enriched: boolean // false until enrich-card populates grammar tables
  audioReady?: boolean // true once the PL+EN TTS clips are cached in IndexedDB
  pl: string
  en: string                  // primary translation (set at card creation)
  definitions?: string[]      // secondary English senses, filled during enrichment
  left: string
  right: string
  tags: WordType[]
  sourceContext?: {
    sentence: string
    translation: string
    addedFrom: 'sentence-mining' | 'manual' | 'import'
  }
}

export interface VocabVerb extends VocabBase {
  type: 'verb'
  conjugations: VerbConjugations | null
  otherForm: { label: string; word: string } | null
}

export interface VocabNoun extends VocabBase {
  type: 'noun'
  gender: string
  plAlt: string
  declensions: NounDeclensions | null
}

export interface AdjectiveDeclensions {
  cases: string[]
  masculine: string[]
  feminine: string[]
  neuter: string[]
  pluralMasc: string[]
  pluralNonMasc: string[]
}

export interface VocabAdjective extends VocabBase {
  type: 'adjective'
  declensions: AdjectiveDeclensions | null
  // Degrees of comparison (stopień wyższy / najwyższy), masc. nom. sg. Filled
  // during enrichment; empty string when the adjective isn't gradable, and
  // absent on cards enriched before this field existed.
  comparative?: string
  superlative?: string
}

export interface VocabUnknown extends VocabBase {
  type: 'unknown'
  info?: string
}

export type VocabEntry = VocabVerb | VocabNoun | VocabAdjective | VocabUnknown

// ─── Spaced-repetition review state (stored separately from VocabEntry) ───────

export interface ReviewState {
  interval: number          // days until next review
  easeFactor: number        // SM-2 ease factor, starts at 2.5
  dueDate: string           // ISO date 'YYYY-MM-DD'
  lastReviewed: string | null
  reviewCount: number
  // Progress toward "conquerable" in the flashcard game. Each left-swipe adds
  // 1 (normal mode) or 1.5 (hard mode); a right-swipe resets it. At >= 3 the
  // swipe-up-hold conquer gesture unlocks (3 normal / 2 hard left-swipes).
  conquerProgress?: number
  // True only when the card was explicitly conquered (swipe-up-hold / button) —
  // NOT inferred from the SRS interval, which grows past 180 on its own.
  conquered?: boolean
}

// ─── Sentence entries (generated by scripts/generate-sentences.js) ────────────

interface SentenceBase {
  id: string
  cardLemma: string
  targetForm: string
  polish: string
  english: string
  languageToolPassed: boolean
  approved: boolean
}

export interface SentenceNoun extends SentenceBase {
  cardType: 'noun'
  targetCase: string
  targetNumber: string
}

export interface SentenceVerb extends SentenceBase {
  cardType: 'verb'
  targetPronoun: string
  targetTense: string
}

export interface SentenceAdjective extends SentenceBase {
  cardType: 'adjective'
  targetGender: string
  targetCase: string
  targetNumber: string
}

export type SentenceEntry = SentenceNoun | SentenceVerb | SentenceAdjective
